#real life example: építünk egy ikerházat egy adot telken

#program: a ház építési terve, nem használ semmilyen erőforrást amíg el nem kezdődik az építkezés
#process: a ház tényleges építési folyamata, már erőforrásokat használva, ikerház miatt lehet 2 oldal 2 külön process
#thread: falazás, festés, eletronika, gépészet stb. egy process-en belül, vagyis egy ház-oldalon belül
#stack: minden thread szerszámos ládája
#heap: építészeti rajz