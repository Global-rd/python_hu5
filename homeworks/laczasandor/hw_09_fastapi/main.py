import uuid
from contextlib import asynccontextmanager

from fastapi import Depends, FastAPI, HTTPException
from sqlmodel import Field, Session, SQLModel, create_engine, select

DATABASE_URL = "sqlite:///webshop.db"
engine = create_engine(DATABASE_URL, connect_args={"check_same_thread": False})


# ---------- Models ----------

class ItemBase(SQLModel):
    item_name: str
    quantity: int = Field(ge=0)
    price: int = Field(ge=0)  # in HUF, whole number
    category: str | None = None  # optional field


class Item(ItemBase, table=True):
    """Database table – the id is generated by the server (uuid1)."""
    id: uuid.UUID = Field(default_factory=uuid.uuid1, primary_key=True)


class ItemCreate(ItemBase):
    """No id needs to be provided when creating an item."""
    pass


class ItemRead(ItemBase):
    """Response model – includes the id."""
    id: uuid.UUID


class ItemUpdate(SQLModel):
    """All fields are optional on update – only the provided ones change."""
    item_name: str | None = None
    quantity: int | None = Field(default=None, ge=0)
    price: int | None = Field(default=None, ge=0)
    category: str | None = None


# ---------- Database ----------

def create_db_and_tables() -> None:
    SQLModel.metadata.create_all(engine)


def get_session():
    with Session(engine) as session:
        yield session


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Create the tables on startup
    create_db_and_tables()
    yield


app = FastAPI(title="Webshop product inventory", lifespan=lifespan)


def get_item_or_404(item_id: uuid.UUID, session: Session) -> Item:
    item = session.get(Item, item_id)
    if item is None:
        raise HTTPException(status_code=404, detail="Item not found")
    return item


# ---------- Endpoints ----------

@app.get("/items", response_model=list[ItemRead])
def list_items(session: Session = Depends(get_session)):
    """List all items."""
    return session.exec(select(Item)).all()


@app.get("/items/{item_id}", response_model=ItemRead)
def get_item(item_id: uuid.UUID, session: Session = Depends(get_session)):
    """Get a single item by id."""
    return get_item_or_404(item_id, session)


@app.post("/items", response_model=ItemRead, status_code=201)
def create_item(item: ItemCreate, session: Session = Depends(get_session)):
    """Add a new item – the generated id is returned in the response."""
    db_item = Item.model_validate(item)
    session.add(db_item)
    session.commit()
    session.refresh(db_item)
    return db_item


@app.put("/items/{item_id}", response_model=ItemRead)
def update_item(item_id: uuid.UUID, item: ItemUpdate,
                session: Session = Depends(get_session)):
    """Update an item by id (only the provided fields)."""
    db_item = get_item_or_404(item_id, session)
    update_data = item.model_dump(exclude_unset=True)
    db_item.sqlmodel_update(update_data)
    session.add(db_item)
    session.commit()
    session.refresh(db_item)
    return db_item


@app.delete("/items/{item_id}")
def delete_item(item_id: uuid.UUID, session: Session = Depends(get_session)):
    """Delete an item by id."""
    db_item = get_item_or_404(item_id, session)
    session.delete(db_item)
    session.commit()
    return {"ok": True, "deleted_id": str(item_id)}
